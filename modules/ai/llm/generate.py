import time
from typing import Callable, TypeVar

from langchain_core.exceptions import OutputParserException
from langchain_core.messages import AIMessage, BaseMessage, HumanMessage
from loguru import logger
from pydantic import BaseModel, ValidationError

from modules.ai.errors import ai_generation_failed, ai_unavailable
from modules.ai.prompts.loader import shared

from .chain import NoProviderAvailable, get_chain
from .settings import feature_settings


S = TypeVar("S", bound=BaseModel)
R = TypeVar("R")


def default_fix_message(error: str) -> BaseMessage:
    return HumanMessage(content=shared.render("shared/fix", error=error))


async def generate_structured(
    feature: str,
    schema: type[S],
    messages: list[BaseMessage],
    convert: Callable[[S], R],
    *,
    fix_message: Callable[[str], BaseMessage] = default_fix_message,
) -> R:
    """Ask the feature's providers for `schema`, then `convert` the reply.

    `convert` raises ValueError (pydantic's ValidationError is one) to reject
    a draft; the error goes back to the model to fix. Gives up after the
    feature's MAX_ATTEMPTS calls or DEADLINE_SECONDS, whichever comes first.

    Raises ai_unavailable (503) when no provider answers and
    ai_generation_failed (502) when none of the answers was usable."""
    settings = feature_settings(feature)
    chain = get_chain(feature)
    deadline = time.monotonic() + settings.deadline_seconds
    error = "the model returned nothing"

    for attempt in range(1, settings.max_attempts + 1):
        if attempt > 1 and time.monotonic() >= deadline:
            error = f"deadline of {settings.deadline_seconds:g}s reached; last error: {error}"
            break
        try:
            draft, provider = await chain.ainvoke_structured(schema, messages)
        except (OutputParserException, ValidationError) as e:
            # the reply didn't fit the schema; ask again from scratch
            error = str(e)
            logger.warning("AI {} attempt {} unparseable: {}", feature, attempt, error)
            continue
        except NoProviderAvailable as e:
            logger.error("AI {}: no provider answered ({})", feature, e)
            raise ai_unavailable() from e
        if draft is None:
            continue

        try:
            result = convert(draft)
        except ValueError as e:
            error = str(e)
            logger.warning("AI {} attempt {} by {} rejected: {}", feature, attempt, provider, error)
            messages = [*messages, AIMessage(content=draft.model_dump_json()), fix_message(error)]
            continue
        logger.info("AI {} generated by {} in {} attempt(s)", feature, provider, attempt)
        return result

    logger.error("AI {} gave up: {}", feature, error)
    raise ai_generation_failed()
